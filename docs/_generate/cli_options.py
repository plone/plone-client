"""Generate the arguments and options of every command, from the Typer app."""

from common import cell
from common import publish
from plone_client.cli import app
from typer.main import get_command
from typing import Any

import re
import sys


HEADER = "<!-- Generated by docs/_generate/cli_options.py: do not edit. -->"


def default_of(param: Any) -> str:
    """The default of an option, for the table.

    :param param: The parameter.
    :returns: The value in backticks, or a dash when there is none.
    """
    value = param.default
    if callable(value) or value in (None, "", False, (), []):
        return "—"
    return f"`{value}`"


def rows(params: list[Any]) -> list[str]:
    """Table rows of the parameters of a command.

    :param params: The parameters.
    :returns: Lines of Markdown.
    """
    lines: list[str] = []
    for param in params:
        if getattr(param, "hidden", False) or param.name == "help":
            continue
        if param.param_type_name == "argument":
            name = f"`{param.human_readable_name}`"
        else:
            names = sorted(param.opts, key=len, reverse=True)
            name = ", ".join(f"`{item}`" for item in (*names, *param.secondary_opts))
        kind = "flag" if getattr(param, "is_flag", False) else param.type.name
        required = "yes" if param.required else "no"
        text = cell(getattr(param, "help", "") or "").replace("<", "\\<")
        # linkify takes a bare file name for a web address
        text = re.sub(r"(?<![`\w])([\w.-]+\.md)\b", r"`\1`", text)
        lines.append(f"| {name} | {kind} | {required} | {default_of(param)} | {text} |")
    return lines


def walk(command: Any, path: list[str]) -> list[tuple[list[str], Any]]:
    """Every command under a group.

    :param command: The group or command.
    :param path: Names so far.
    :returns: Pairs of names and commands, in the order of the help.
    """
    found = [(path, command)] if path else []
    if hasattr(command, "commands"):
        for name, child in sorted(command.commands.items()):
            found.extend(walk(child, [*path, name]))
    return found


def page() -> str:
    """The Markdown page.

    :returns: Its text.
    """
    out = [HEADER, "", "<!-- vale off -->", ""]
    for path, command in walk(get_command(app), []):
        name = " ".join(path)
        out += [f"({'cli-' + '-'.join(path)})=", "", f"### `{name}`", ""]
        if command.help:
            summary = " ".join(command.help.split("\n\n")[0].split())
            out += [re.sub(r"(?<![`\w])([\w.-]+\.md)\b", r"`\1`", summary), ""]
        lines = rows(command.params)
        if hasattr(command, "commands"):
            children = ", ".join(f"`{child}`" for child in sorted(command.commands))
            out += [f"Subcommands: {children}.", ""]
        if lines:
            out += [
                "| Argument or option | Type | Required | Default | Description |",
                "|---|---|---|---|---|",
                *lines,
                "",
            ]
    return "\n".join(out).rstrip() + "\n"


def global_options() -> str:
    """The options of the root command.

    :returns: A Markdown table.
    """
    lines = rows(get_command(app).params)
    header = [
        HEADER,
        "",
        "<!-- vale off -->",
        "",
        "| Option | Type | Required | Default | Description |",
        "|---|---|---|---|---|",
    ]
    return "\n".join([*header, *lines]) + "\n"


if __name__ == "__main__":
    codes = (
        publish("cli-commands.md", page()),
        publish("cli-global-options.md", global_options()),
    )
    sys.exit(max(codes))
