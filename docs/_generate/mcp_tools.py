"""Generate the tables of tools and resources, from the MCP server itself."""

from common import cell
from common import publish
from plone_client import PloneClient
from plone_client.mcp_server import build_server
from plone_client.mcp_server import INSTRUCTIONS
from plone_client.mcp_server import Site
from plone_client.mcp_server import Sites
from typing import Any

import asyncio
import sys


URL = "https://example.org"


def several_sites() -> Sites:
    """Two sites, as ``--site`` builds them; nothing connects to them.

    :returns: A writable and a read-only site.
    """
    return Sites([
        Site(
            name="one",
            url=URL,
            read_only=False,
            client=PloneClient(URL),
        ),
        Site(
            name="two",
            url=URL + ".br",
            read_only=True,
            client=PloneClient(URL + ".br", read_only=True),
        ),
    ])


def behavior(tool: Any) -> str:
    """Say what a tool does to the site, from its annotations.

    :param tool: The tool.
    :returns: ``read``, ``adds``, ``changes`` or ``removes``.
    """
    hints = tool.annotations
    if hints.read_only_hint:
        return "reads"
    if hints.destructive_hint is False:
        return "adds"
    return "changes, repeatable" if hints.idempotent_hint else "changes"


def kind(schema: dict[str, Any]) -> str:
    """Say that an argument is a list, the type a model is most likely to miss.

    :param schema: JSON schema of the argument.
    :returns: A note, or nothing.
    """
    options = schema.get("anyOf", [schema])
    is_list = any(option.get("type") == "array" for option in options)
    return " (list)" if is_list else ""


def summary(tool: Any) -> str:
    """First paragraph of a tool's description.

    :param tool: The tool.
    :returns: One line.
    """
    text = cell((tool.description or "").split("\n\n")[0])
    return text.replace("plone.restapi", "`plone.restapi`")


async def tools_page() -> str:
    """The table of tools.

    :returns: Markdown.
    """
    client = PloneClient(URL)
    every = {tool.name: tool for tool in await build_server(client).list_tools()}
    several = await build_server(several_sites()).list_tools()
    # The other tools only gain a site argument with several sites
    every.update({tool.name: tool for tool in several if tool.name not in every})
    read_only = build_server(PloneClient(URL, read_only=True))
    readable = {tool.name for tool in await read_only.list_tools()}
    lines = [
        "<!-- Generated by docs/_generate/mcp_tools.py: do not edit. -->",
        "",
        f"The server has {len(every)} tools.",
        "`list_sites` is offered only with several sites.",
        "The column *Read-only site* says whether a server of one read-only site offers the tool.",
        "",
        "| Tool | Arguments | Effect | Read-only site | Description |",
        "|---|---|---|---|---|",
    ]
    for name in sorted(every):
        tool = every[name]
        schema = tool.input_schema
        required = schema.get("required", [])
        arguments = [
            ("`" + key + "`" if key in required else "`" + key + "`?") + kind(value)
            for key, value in schema.get("properties", {}).items()
        ]
        offered = "yes" if name in readable or name == "list_sites" else "no"
        lines.append(
            f"| `{name}` | {', '.join(arguments) or '—'} | {behavior(tool)} "
            f"| {offered} | {summary(tool)} |"
        )
    return "\n".join(lines) + "\n"


async def resources_page() -> str:
    """The table of resources.

    :returns: Markdown.
    """
    server = build_server(PloneClient(URL))
    fixed = await server.list_resources()
    templates = await server.list_resource_templates()
    lines = [
        "<!-- Generated by docs/_generate/mcp_tools.py: do not edit. -->",
        "",
        "| URI | Media type | Description |",
        "|---|---|---|",
    ]
    for uri, media, description in sorted(
        [(str(item.uri), item.mime_type, item.description) for item in fixed]
        + [(item.uri_template, item.mime_type, item.description) for item in templates]
    ):
        text = cell((description or "").split("\n\n")[0])
        lines.append(f"| `{uri}` | `{media}` | {text} |")
    return "\n".join(lines) + "\n"


def instructions_page() -> str:
    """The text every server sends, before what depends on its sites.

    :returns: Markdown.
    """
    return f"```text\n{INSTRUCTIONS.strip()}\n```\n"


if __name__ == "__main__":
    codes = (
        publish("mcp-tools.md", asyncio.run(tools_page())),
        publish("mcp-resources.md", asyncio.run(resources_page())),
        publish("mcp-instructions.md", instructions_page()),
    )
    sys.exit(max(codes))
